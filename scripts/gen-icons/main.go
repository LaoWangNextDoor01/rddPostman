// gen-icons 扫描 components/v1/icons/assets 下的 .svg，
// 生成类型化图标变量文件 components/v1/icons/icons_gen.go。
//
// 由 scripts/sync-icons.ps1|.sh 在同步资产后调用；内容无变化时不写文件，
// 避免无意义的 mtime 变动。手工调用：go run ./scripts/gen-icons
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const header = "// Code generated by mygo generate from the catalogs in this directory. DO NOT EDIT.\n\npackage icons\n\n"

// reserved 是包内已占用的标识符（含未来可能加的辅助函数）。
// 图标的 Pascal 名撞上它们时，变量自动追加 Icon 后缀，避免编译冲突。
var reserved = map[string]bool{
	"Get":   true,
	"Names": true,
	"Must":  true,
	"All":   true,
}

// resolveVarName 返回某个图标对应的导出变量名。
// Pascal 名与包内标识符冲突时加 Icon 后缀，例如 Lucide "get" → GetIcon。
func resolveVarName(name string) (string, bool) {
	p := pascal(name)
	if reserved[p] {
		return p + "Icon", true
	}
	return p, false
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen-icons:", err)
		os.Exit(1)
	}
}

func run() error {
	dir := filepath.Join("components", "v1", "icons", "assets")
	out := filepath.Join("components", "v1", "icons", "icons_gen.go")

	entries, err := os.ReadDir(dir)
	if err != nil {
		return fmt.Errorf("读资产目录: %w", err)
	}
	names := make([]string, 0, len(entries))
	for _, e := range entries {
		if name, ok := strings.CutSuffix(e.Name(), ".svg"); ok {
			names = append(names, name)
		}
	}
	if len(names) == 0 {
		return fmt.Errorf("assets 目录下没有 .svg，先运行 scripts/sync-icons.ps1|.sh")
	}
	sort.Strings(names)

	var b strings.Builder
	b.WriteString(header)
	b.WriteString("// 类型化图标变量：kebab-case → PascalCase，IDE 可补全；新图标在清单加行并同步后自动出现。\n")
	b.WriteString("// 与包内函数冲突的图标自动加 Icon 后缀（如 Lucide \"get\" → GetIcon）。\n")
	b.WriteString("var (\n")
	seen := map[string]string{}
	for _, n := range names {
		varName, renamed := resolveVarName(n)
		if prev, dup := seen[varName]; dup {
			return fmt.Errorf("%q 与 %q 的变量名都是 %s，请在 icons.txt 里去掉一个", prev, n, varName)
		}
		seen[varName] = n
		if renamed {
			fmt.Fprintf(&b, "\t%s = Get(%q) // Lucide %q：与包内标识符冲突，自动加 Icon 后缀\n", varName, n, n)
			fmt.Printf("注意：%q 与包内标识符冲突，变量名改为 %s\n", n, varName)
			continue
		}
		fmt.Fprintf(&b, "\t%s = Get(%q)\n", varName, n)
	}
	b.WriteString(")\n")

	if old, err := os.ReadFile(out); err == nil && string(old) == b.String() {
		fmt.Println("icons_gen.go 无变化，跳过写入")
		return nil
	}
	if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
		return fmt.Errorf("写入 %s: %w", out, err)
	}
	fmt.Printf("已生成 %s（%d 个图标）\n", out, len(names))
	return nil
}

// pascal 把 kebab-case 转成 PascalCase：user-round → UserRound。
func pascal(name string) string {
	var sb strings.Builder
	for _, part := range strings.Split(name, "-") {
		if part == "" {
			continue
		}
		sb.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return sb.String()
}
